const platformSourceLabels = {
    chp: 'CHP-BC — Platform Priorities',
    communist: 'Communist Party of BC — Our Platform (2026)',
    freedom: 'Freedom Party of BC — Our Platform',
    onebc: 'OneBC — Our Priorities',
};

export function getPlatformItems(party) {
    return [...party.promises, ...(additionalPromises[party.id] || [])].map(
        ([topic, summary]) => {
            const detail = platformDetails[party.id][topic];
            const sources = detail.sources || [
                {
                    url: party.platform,
                    label:
                        platformSourceLabels[party.id] ||
                        `${party.name} — Party platform`,
                },
            ];
            return {
                topic,
                summary,
                ...detail,
                points: detail.points.map((text, index) => ({
                    text,
                    sourceIndices: detail.pointSources?.[index] || [0],
                })),
                note: [
                    detail.note,
                    ['freedom', 'canwest'].includes(party.id)
                        ? party.status
                        : undefined,
                ]
                    .filter(Boolean)
                    .join(' '),
                sources,
            };
        },
    );
}
